#!/usr/bin/env python3
"""Generates main/Source/WorldMap.c from Natural Earth land polygons.

Input: ne_110m_land.geojson from https://github.com/nvkelso/natural-earth-vector (geojson/ folder).
Natural Earth data is in the public domain.

Usage: python gen_world_map.py ne_110m_land.geojson ../main/Source/WorldMap.c
"""
import json
import sys


def rings_of(geometry):
    if geometry["type"] == "Polygon":
        return geometry["coordinates"]
    if geometry["type"] == "MultiPolygon":
        return [ring for polygon in geometry["coordinates"] for ring in polygon]
    return []


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    rings = []
    for feature in data["features"]:
        for ring in rings_of(feature["geometry"]):
            points = []
            for lon, lat in ring:
                p = (round(lon * 100), round(lat * 100))
                if not points or points[-1] != p:
                    points.append(p)
            if len(points) > 1 and points[0] == points[-1]:
                points.pop()
            if len(points) >= 3:
                rings.append(points)

    total = sum(len(r) for r in rings)
    with open(sys.argv[2], "w", newline="\n") as out:
        out.write("// Generated by tools/gen_world_map.py from Natural Earth ne_110m_land (public domain). Do not edit.\n")
        out.write('#include "WorldMap.h"\n\n')
        out.write(f"const uint16_t WORLD_MAP_RING_COUNT = {len(rings)};\n\n")
        out.write("const uint16_t WORLD_MAP_RING_LENGTHS[] = {\n")
        for i in range(0, len(rings), 16):
            out.write("    " + ", ".join(str(len(r)) for r in rings[i:i + 16]) + ",\n")
        out.write("};\n\n")
        out.write(f"const int16_t WORLD_MAP_POINTS[{total * 2}] = {{\n")
        flat = [v for r in rings for p in r for v in p]
        for i in range(0, len(flat), 16):
            out.write("    " + ", ".join(str(v) for v in flat[i:i + 16]) + ",\n")
        out.write("};\n")
    print(f"{len(rings)} rings, {total} points")
    return 0


if __name__ == "__main__":
    sys.exit(main())
